/**
 * 47都道府県の「県・都・府」を落とした呼び方（「香川」「東京」「大阪」）。
 * 行き先に「香川」とだけ書く人は多いので、表に並べずここで機械的に作る。
 */
const SHORT_PREF: Record<string, string> = {};
for (const full of PREFECTURES) {
  // 正式名そのものも引けるようにする。北海道は接尾辞が無く略称が作られないため、
  // これが無いと「北海道」だけが漏れる。
  SHORT_PREF[full] = full;
  const short = full.replace(/(都|府|県)$/, "");
  if (short !== full) SHORT_PREF[short] = full;
}

const LOOKUP: Record<string, string> = { ...SHORT_PREF, ...AREA_PREF };

// 長い地名から先に照合する。「河口湖」が「湖」より、「黒川温泉」が「黒川」より先に当たる。
const AREA_KEYS = Object.keys(LOOKUP).sort((a, b) => b.length - a.length);

/**
 * 市名・観光地名から都道府県を推定する（「金沢」→「石川県」）。
 * 表に無ければ null。都道府県名がそのまま書かれている場合は `prefectureOf` が先に拾う。
 */
export function prefectureFromArea(text: string | undefined): string | null {
  const t = text?.trim();
  if (!t) return null;
  const key = AREA_KEYS.find((k) => t.includes(k));
  return key ? LOOKUP[key] : null;
}

/**
 * 行き先の自由文・住所リストから都道府県を割り出す。
 * 都道府県名が書かれていればそれを、無ければ市名・観光地名から推定する。
 */
export function resolvePrefecture(texts: (string | undefined)[]): string | null {
  return tripRegion(texts) ?? texts.map((t) => prefectureFromArea(t)).find((p) => p) ?? null;
}
